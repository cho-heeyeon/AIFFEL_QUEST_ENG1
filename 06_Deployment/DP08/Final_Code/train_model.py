from sklearn.linear_model import LogisticRegression
import joblib

# ==========================================
# 1. 교육용 가상 학습 데이터
#
# X = [진동값, 오류 발생 횟수, 전류값]
# y = 1(정상), 0(이상)
#
# 실제 설비에서 측정한 데이터가 아니라
# 모델 배포 학습을 위한 가상 데이터입니다.
# ==========================================

X = [
    # 정상 데이터
    [1.2, 0, 8.5],
    [1.4, 0, 8.8],
    [1.5, 1, 9.0],
    [1.7, 0, 9.2],
    [1.8, 1, 9.4],
    [2.0, 1, 9.6],

    # 이상 데이터
    [4.2, 4, 13.5],
    [4.5, 5, 14.2],
    [4.8, 4, 13.8],
    [5.0, 6, 14.5],
    [5.1, 7, 15.0],
    [5.5, 8, 15.5],
]

y = [
    1, 1, 1, 1, 1, 1,   # 정상
    0, 0, 0, 0, 0, 0    # 이상
]


# ==========================================
# 2. LogisticRegression 모델 생성
# ==========================================

model = LogisticRegression(max_iter=1000)


# ==========================================
# 3. 모델 학습
# ==========================================

model.fit(X, y)

print("모델 학습 완료")


# ==========================================
# 4. 모델 저장
# ==========================================

joblib.dump(model, "equipment_model.pkl")

print("equipment_model.pkl 저장 완료")


# ==========================================
# 5. 테스트 예측
# ==========================================

sample = [[1.5, 1, 9.0]]

prediction = model.predict(sample)[0]

if prediction == 1:
    print("예측 결과: 정상")
else:
    print("예측 결과: 이상")